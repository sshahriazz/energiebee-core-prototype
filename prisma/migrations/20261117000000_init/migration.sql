  IF NEW.plan_run_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM plan_run r JOIN device d ON d.site_id = r.site_id WHERE r.id = NEW.plan_run_id AND d.id = NEW.device_id) THEN RAISE EXCEPTION 'command: the plan run belongs to another home'; END IF;
