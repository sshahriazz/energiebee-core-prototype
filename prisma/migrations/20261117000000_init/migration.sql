CREATE FUNCTION trg_plan_slot_checks() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM plan_run r WHERE r.id = NEW.plan_run_id AND NEW.slot_start >= r.plan_start AND (NEW.slot_start - r.plan_start) % r.slot_s = 0 AND NEW.slot_start < r.plan_start + r.horizon_h * 3600) THEN RAISE EXCEPTION 'plan_slot: slot_start is not on the run''s slot grid or is outside its horizon'; END IF;
  IF EXISTS (SELECT 1 FROM plan_run r WHERE r.id = NEW.plan_run_id AND NEW.start_offset_min * 60 >= r.slot_s) THEN RAISE EXCEPTION 'plan_slot: start_offset_min must be less than the slot'; END IF;
  IF NOT EXISTS (SELECT 1 FROM plan_run_device p WHERE p.plan_run_id = NEW.plan_run_id AND p.device_id = NEW.device_id AND p.role IN ('controlled', 'aggregate')) THEN RAISE EXCEPTION 'plan_slot: device not planned by this run (plan_run_device role controlled or aggregate)'; END IF;
  IF NOT EXISTS (SELECT 1 FROM device d JOIN device_action a ON a.device_kind = d.kind AND a.action = NEW.action WHERE d.id = NEW.device_id) THEN RAISE EXCEPTION 'plan_slot: action not defined in device_action for this device kind'; END IF;
  IF EXISTS (SELECT 1 FROM device_capability c WHERE c.device_id = NEW.device_id AND c.action = NEW.action AND c.supported = 0) THEN RAISE EXCEPTION 'plan_slot: the device cannot deliver this action (device_capability supported = 0)'; END IF;
  RETURN NEW;
END $$;
