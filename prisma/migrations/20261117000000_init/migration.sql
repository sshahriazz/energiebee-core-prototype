-- EnergieBee core: the first Postgres schema, translated from the final SQLite schema (schema.sql and its 43 deltas).
-- Rules kept from SQLite: every CHECK, unique key, partial index and trigger. Postgres-native where better:
-- exclusion constraints for "no overlapping current periods" (rate_interval, tariff_agreement, site_group_member),
-- IS JSON checks, double precision for every real number, bigint for every integer (ids, seconds, milliseconds).
CREATE EXTENSION IF NOT EXISTS btree_gist;

