-- Erasure and append-only (fix list R14, plan 1.7).
-- Facts and raw receipts are append-only in the database itself: a fact changes only by being superseded (superseded_at set
-- once, nothing else), a raw receipt never changes, and neither is ever deleted, except inside a logged erasure. An erasure
-- is a row of erasure_log, opened in the same transaction (core: src/core/erasure.js): a whole home deleted for good, history
-- past its retention period, a copy anonymised (the test fixture) or synthetic data replaced. The log keeps what was
-- removed (counts), never the data.
CREATE TABLE erasure_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind text NOT NULL CHECK (kind IN ('home', 'retention', 'anonymise', 'synthetic')),
  site_id bigint,                -- the home erased (no foreign key: the home is gone)
  site_uid uuid,
  reason text NOT NULL CHECK (length(reason) > 0),
  started_at bigint NOT NULL,
  finished_at bigint,
  removed text CHECK (removed IS NULL OR removed IS JSON OBJECT),
  CHECK (kind <> 'home' OR site_id IS NOT NULL)
);

CREATE FUNCTION erasure_open() RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT EXISTS (SELECT 1 FROM erasure_log WHERE id = NULLIF(current_setting('energiebee.erasure', true), '')::bigint AND finished_at IS NULL)
$$;

CREATE FUNCTION trg_fact_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF erasure_open() THEN RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END; END IF;
  IF TG_OP = 'DELETE' THEN RAISE EXCEPTION 'append-only: a fact is never deleted (only by a logged erasure)'; END IF;
  IF OLD.superseded_at IS NOT NULL OR NEW.superseded_at IS NULL OR (to_jsonb(NEW) - 'superseded_at') <> (to_jsonb(OLD) - 'superseded_at') THEN
    RAISE EXCEPTION 'append-only: a fact changes only by being superseded once (a new value is a new version)';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER reading_append_only BEFORE UPDATE OR DELETE ON reading FOR EACH ROW EXECUTE FUNCTION trg_fact_append_only();
CREATE TRIGGER interval_fact_append_only BEFORE UPDATE OR DELETE ON interval_fact FOR EACH ROW EXECUTE FUNCTION trg_fact_append_only();

-- A forecast is never superseded (each issue is its own row): it never changes.
CREATE FUNCTION trg_unchanging() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF erasure_open() THEN RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END; END IF;
  RAISE EXCEPTION 'append-only: % rows never change and are never deleted (only by a logged erasure)', TG_TABLE_NAME;
END $$;
CREATE TRIGGER forecast_fact_append_only BEFORE UPDATE OR DELETE ON forecast_fact FOR EACH ROW EXECUTE FUNCTION trg_unchanging();
CREATE TRIGGER raw_payload_append_only BEFORE UPDATE OR DELETE ON raw_payload FOR EACH ROW EXECUTE FUNCTION trg_unchanging();

-- A home's raw files are encrypted with the home's own key (AES-256-GCM, src/core/facts.js). Deleting the home deletes the
-- key, so its raw files cannot be read again, including in file backups (crypto-shredding). Public data (price lists, grid
-- data) is not encrypted. In production the keys belong in a key management service; here they are rows.
CREATE TABLE home_key (
  site_id bigint PRIMARY KEY REFERENCES site(id) DEFERRABLE,
  key bytea NOT NULL CHECK (length(key) = 32),
  created_at bigint NOT NULL
);
