-- Phase T.1/T.2: tariff price runs (docs/thing-platform-plan.md, docs/thing-model.md section 8). One row per price change of
-- a tariff and register: what the tariff charges, from when to when, ex tax. Rate rows that follow each other with the same
-- price, estimate flag and origin are one run, so a flat tariff is one row however many rate rows say it and no grid is fixed
-- into the data (the slot length of a home is chosen when a home reads them). Fixed charges are runs too: component 'standing',
-- 'fixed' or 'capacity' with their charge period, so a fixed charge becomes a share of each slot from the same table.
--
-- The table describes NOW (a serving table, rebuilt from rate_interval by src/core/price-run-store.js, which replaces a
-- tariff's rows as a whole): a build "as known at" a past moment computes its runs in memory from the rate rows as they stood
-- then, with the same code (src/core/price-runs.js), and never reads this table. Rows with site_id are the runs of a home's own
-- rate rows (they win over the tariff's for that home); the others are shared by every home on the tariff.
CREATE TABLE tariff_price_run (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tariff_id bigint NOT NULL,
  site_id bigint,
  component text NOT NULL CHECK (component IN ('unit', 'standing', 'fixed', 'capacity')),
  register text NOT NULL CHECK (length(register) > 0),
  charge_period text CHECK (charge_period IN ('day', 'month', 'year')),
  payment_method text NOT NULL DEFAULT 'ANY',
  valid_from bigint NOT NULL,
  valid_to bigint,
  price_ex_vat double precision NOT NULL,
  estimated bigint NOT NULL DEFAULT 0 CHECK (estimated IN (0, 1)),
  origin text CHECK (origin IS NULL OR origin IN ('sourced', 'provider', 'user', 'derived', 'placeholder', 'synthetic')),
  lineage jsonb NOT NULL,
  built_at bigint NOT NULL,
  CHECK (valid_to IS NULL OR valid_to > valid_from),
  CHECK (CASE component WHEN 'unit' THEN charge_period IS NULL WHEN 'standing' THEN charge_period IS NULL OR charge_period = 'day' ELSE charge_period IS NOT NULL END),
  CONSTRAINT price_run_no_overlap EXCLUDE USING gist (tariff_id WITH =, component WITH =, register WITH =, (COALESCE(charge_period, '')) WITH =, payment_method WITH =, (COALESCE(site_id, 0)) WITH =, int8range(valid_from, COALESCE(valid_to, 9000000000)) WITH &&)
);
ALTER TABLE tariff_price_run ADD FOREIGN KEY (tariff_id) REFERENCES tariff (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE;
ALTER TABLE tariff_price_run ADD FOREIGN KEY (site_id) REFERENCES site (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE;
CREATE INDEX tariff_price_run_tariff_time ON tariff_price_run (tariff_id, valid_from);
CREATE INDEX tariff_price_run_site ON tariff_price_run (site_id) WHERE site_id IS NOT NULL;

COMMENT ON COLUMN tariff_price_run.site_id IS 'set only for the runs of a home-specific rate row (it wins over the tariff''s own for that home)';
COMMENT ON COLUMN tariff_price_run.valid_from IS 's';
COMMENT ON COLUMN tariff_price_run.valid_to IS 's; NULL = open-ended';
COMMENT ON COLUMN tariff_price_run.price_ex_vat IS 'minor units per kWh (unit), per local day (standing) or per kW per charge period (capacity) or per charge period (fixed), excluding taxes';
COMMENT ON COLUMN tariff_price_run.estimated IS '1 = a cautious default by a stated rule (a Tempo colour not published yet), not a published price';
COMMENT ON COLUMN tariff_price_run.lineage IS 'the rate_interval rows the run was made from: {"rate_ids": [first ids], "n": how many}';
COMMENT ON COLUMN tariff_price_run.built_at IS 's';
