-- Phase T.3 to T.5: the home's price slots, the freshness of the runs, and the queue of price changes.
--
-- supply_price_slot: what one supply point of one home pays for one slot, at the home's slot length: the agreement in force,
-- the tariff's price runs, the home's own rows and its meter's windows, its taxes, dispatches, and the fixed charges as a share
-- of the slot (docs/thing-model.md section 8). A serving table: it describes NOW and is rebuilt by src/core/supply-price.js.
-- A build "as known at" a past moment never reads it; it computes its slots in memory from the same pure code.
-- `point` names the supply point: the meter kind ('meter_import', 'meter_export', 'meter_gas'), or 'device:<id>' for a sub-meter
-- with a tariff of its own (R11). device_id is the meter device the agreement is on (it will point at the meter thing in Phase 1.3);
-- both are NULL on a row that records "no agreement at this slot", so a slot with no agreement is known and not recomputed.
-- `stamp` fingerprints every input the slot was made from (agreements, rate rows, taxes, windows, dispatches, the home's settings,
-- the slot length): a row is read only while its stamp equals the current one, so a change that bypassed the write functions
-- can never be served stale.
CREATE TABLE supply_price_slot (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id bigint NOT NULL,
  point text NOT NULL CHECK (length(point) > 0),
  device_id bigint,
  tariff_id bigint,
  slot_start bigint NOT NULL,
  dur_s integer NOT NULL CHECK (dur_s > 0),
  register text,
  unit_ex double precision,
  supply_ex double precision,
  vat double precision,
  levy double precision,
  unit_inc double precision,
  fixed_inc double precision NOT NULL DEFAULT 0,
  weighted bigint NOT NULL DEFAULT 0 CHECK (weighted IN (0, 1)),
  estimated bigint NOT NULL DEFAULT 0 CHECK (estimated IN (0, 1)),
  capacity_unknown bigint NOT NULL DEFAULT 0 CHECK (capacity_unknown IN (0, 1)),
  tax_source text,
  tax_unverified bigint NOT NULL DEFAULT 0 CHECK (tax_unverified IN (0, 1)),
  lineage jsonb NOT NULL,
  stamp text NOT NULL,
  built_at bigint NOT NULL,
  CHECK ((device_id IS NULL) = (tariff_id IS NULL)),
  CHECK (device_id IS NOT NULL OR (unit_ex IS NULL AND vat IS NULL AND fixed_inc = 0)),
  CONSTRAINT supply_price_slot_key UNIQUE (site_id, point, dur_s, slot_start)
);
ALTER TABLE supply_price_slot ADD FOREIGN KEY (site_id) REFERENCES site (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE;
ALTER TABLE supply_price_slot ADD FOREIGN KEY (device_id) REFERENCES device (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE;
ALTER TABLE supply_price_slot ADD FOREIGN KEY (tariff_id) REFERENCES tariff (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE;
CREATE INDEX supply_price_slot_tariff ON supply_price_slot (tariff_id) WHERE tariff_id IS NOT NULL;
CREATE INDEX supply_price_slot_device ON supply_price_slot (device_id) WHERE device_id IS NOT NULL;

COMMENT ON COLUMN supply_price_slot.point IS 'the supply point: a meter kind, or device:<id> for a sub-meter with its own tariff';
COMMENT ON COLUMN supply_price_slot.slot_start IS 's';
COMMENT ON COLUMN supply_price_slot.unit_ex IS 'minor units per kWh before percentage taxes (supplier price + per-kWh levies); NULL = no price known for the slot, never guessed';
COMMENT ON COLUMN supply_price_slot.supply_ex IS 'the supplier''s own unit price, ex every tax';
COMMENT ON COLUMN supply_price_slot.vat IS 'percentage taxes on unit_ex: the price paid is unit_ex x (1 + vat)';
COMMENT ON COLUMN supply_price_slot.unit_inc IS 'unit_ex x (1 + vat), minor units per kWh, taxes included';
COMMENT ON COLUMN supply_price_slot.fixed_inc IS 'the fixed charges (standing, monthly, yearly, capacity) of this slot, taxes included, minor units';
COMMENT ON COLUMN supply_price_slot.weighted IS '1 = the slot spans two prices; unit_ex is their time-weighted mean over 15-minute samples';
COMMENT ON COLUMN supply_price_slot.estimated IS '1 = a cautious default by a stated rule (a Tempo colour not published yet) was used';
COMMENT ON COLUMN supply_price_slot.lineage IS '{"inputs": [{"what", "origin"}], "tariff": code}: what the price was made of (provenance)';
COMMENT ON COLUMN supply_price_slot.stamp IS 'fingerprint of the inputs; a row of another stamp is stale and ignored';
COMMENT ON COLUMN supply_price_slot.built_at IS 's';

-- The rate rows a tariff's runs were last made from, as a fingerprint: tariff_price_run is read only while this equals the rate
-- rows' own, so rows written by anything (a test, a fix-up in psql) are never served stale.
CREATE TABLE tariff_price_state (
  tariff_id bigint PRIMARY KEY,
  stamp text NOT NULL,
  built_at bigint NOT NULL
);
ALTER TABLE tariff_price_state ADD FOREIGN KEY (tariff_id) REFERENCES tariff (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE;

-- The queue of price changes (T.5): one row per tariff, per country (tax rules) or per home (agreement, meter windows), holding
-- the earliest time the change reaches. The write functions put rows here; src/core/price-queue.js processes each tariff once
-- (rebuilds its runs) and expands it to the homes on it in batches into rebuild_queue. Not a trigger: the as-of rules stay in code.
CREATE TABLE price_dirty (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scope text NOT NULL CHECK (scope IN ('tariff', 'country', 'home')),
  tariff_id bigint,
  country text,
  site_id bigint,
  from_ts bigint NOT NULL,
  reason text,
  marked_at bigint NOT NULL,
  CHECK (CASE scope WHEN 'tariff' THEN tariff_id IS NOT NULL AND country IS NULL AND site_id IS NULL
                    WHEN 'country' THEN country IS NOT NULL AND tariff_id IS NULL AND site_id IS NULL
                    ELSE site_id IS NOT NULL AND tariff_id IS NULL AND country IS NULL END)
);
ALTER TABLE price_dirty ADD FOREIGN KEY (tariff_id) REFERENCES tariff (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE;
ALTER TABLE price_dirty ADD FOREIGN KEY (site_id) REFERENCES site (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE;
CREATE UNIQUE INDEX price_dirty_tariff ON price_dirty (tariff_id) WHERE scope = 'tariff';
CREATE UNIQUE INDEX price_dirty_country ON price_dirty (country) WHERE scope = 'country';
CREATE UNIQUE INDEX price_dirty_home ON price_dirty (site_id) WHERE scope = 'home';
COMMENT ON COLUMN price_dirty.from_ts IS 's; the earliest time the change reaches (a rate row''s start, a rule''s valid_from, an agreement''s start)';
COMMENT ON COLUMN price_dirty.marked_at IS 's';
