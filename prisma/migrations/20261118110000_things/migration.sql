-- The thing graph, additive half (plan Phase 1.1 and 1.2; thing-model sections 3.1 and 3.2): the thing registry, things, their
-- attribute versions, the relation rules and the dated relations between things. Nothing here replaces site, device or their
-- tables: a later step turns every site row into a home thing and every device row into a device thing and repoints the
-- references. Until then a thing's home is `site_id` (a foreign key to site); it becomes home_id -> thing(id) with the rest
-- when the site is folded into the home thing (Phase 1.3b). Time: valid_from / valid_to in seconds, recorded_at /
-- superseded_at in milliseconds, as in the other configuration tables.

-- ───────────── registries (rows owned by the code: src/db/seed/things.js) ─────────────
CREATE FUNCTION thing_ports_valid(p jsonb) RETURNS boolean LANGUAGE sql IMMUTABLE AS $$
  SELECT jsonb_typeof(p) = 'array'
    AND NOT EXISTS (SELECT 1 FROM jsonb_array_elements(p) e
      WHERE jsonb_typeof(e) <> 'object' OR e->>'name' IS NULL OR e->>'dir' IS NULL OR e->>'dir' NOT IN ('in', 'out', 'both') OR e->>'medium' IS NULL)
    AND (SELECT COUNT(*) = COUNT(DISTINCT e->>'name') FROM jsonb_array_elements(p) e)
$$;

CREATE TABLE thing_type (
  type text PRIMARY KEY CHECK (type ~ '^[a-z][a-z0-9_]*$'),
  kind text NOT NULL CHECK (kind IN ('home', 'space', 'device', 'system', 'context')),
  label text NOT NULL CHECK (length(label) > 0),
  capabilities jsonb NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(capabilities) = 'array'),
  -- [{ "name": "charge", "dir": "in" | "out" | "both", "medium": "dc" }]: where energy or heat enters and leaves the type
  ports jsonb NOT NULL DEFAULT '[]' CONSTRAINT thing_type_ports_shape CHECK (thing_ports_valid(ports)),
  attribute_keys jsonb NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(attribute_keys) = 'array'),
  std_ref text,
  description text,
  CONSTRAINT thing_type_kind_key UNIQUE (type, kind)
);

-- Which relations may join which things, and how (thing-model 3.2). The most specific rule that matches decides. A rule names
-- the relation, the kind (and optionally the type) on each side, and what a relation under it must carry:
--   from_ports / to_ports  none: no port; optional: none or a port the type declares; required: a port the type declares
--   flow                   1: a directed flow: the from port sends, the to port receives, both carry the same medium
--   same_type              1: both things have the same type (a replacement)
--   acyclic                1: the relation never forms a cycle (located_in, part_of, replaces)
CREATE TABLE relation_rule (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rel text NOT NULL CHECK (rel ~ '^[a-z][a-z0-9_]*$'),
  from_kind text NOT NULL CHECK (from_kind IN ('home', 'space', 'device', 'system', 'context')),
  from_type text,
  to_kind text NOT NULL CHECK (to_kind IN ('home', 'space', 'device', 'system', 'context')),
  to_type text,
  from_ports text NOT NULL DEFAULT 'none' CHECK (from_ports IN ('none', 'optional', 'required')),
  to_ports text NOT NULL DEFAULT 'none' CHECK (to_ports IN ('none', 'optional', 'required')),
  flow bigint NOT NULL DEFAULT 0 CHECK (flow IN (0, 1)),
  same_type bigint NOT NULL DEFAULT 0 CHECK (same_type IN (0, 1)),
  acyclic bigint NOT NULL DEFAULT 0 CHECK (acyclic IN (0, 1)),
  description text,
  CONSTRAINT relation_rule_from_type_fk FOREIGN KEY (from_type, from_kind) REFERENCES thing_type (type, kind),
  CONSTRAINT relation_rule_to_type_fk FOREIGN KEY (to_type, to_kind) REFERENCES thing_type (type, kind)
);
CREATE UNIQUE INDEX relation_rule_key ON relation_rule (rel, from_kind, COALESCE(from_type, ''), to_kind, COALESCE(to_type, ''));

-- ───────────── things ─────────────
CREATE TABLE thing (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid uuid NOT NULL DEFAULT uuidv7() UNIQUE,   -- the identity outside this database; a hub creates it for the devices it finds
  site_id bigint REFERENCES site (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,   -- the home; none for shared context
  kind text NOT NULL,
  type text NOT NULL,
  name text NOT NULL CHECK (length(btrim(name)) > 0),
  attrs jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(attrs) = 'object'),   -- the current details; every version is in thing_attr_version
  std_ref text,                                -- a Brick / Matter / SAREF class for this thing, when the type's is not enough
  valid_from bigint,                           -- when it began to exist in the home (installed), s
  valid_to bigint,                             -- when it left service (retired), s
  recorded_at bigint NOT NULL DEFAULT (extract(epoch FROM clock_timestamp()) * 1000)::bigint,
  superseded_at bigint,                        -- set when a merge replaces it by another thing (Phase 1.8)
  CONSTRAINT thing_type_fk FOREIGN KEY (type, kind) REFERENCES thing_type (type, kind),
  CONSTRAINT thing_home_unless_context CHECK ((kind = 'context') = (site_id IS NULL)),
  CONSTRAINT thing_valid_window CHECK (valid_from IS NULL OR valid_to IS NULL OR valid_to > valid_from),
  CONSTRAINT thing_record_window CHECK (superseded_at IS NULL OR superseded_at >= recorded_at)
);
CREATE UNIQUE INDEX thing_one_home ON thing (site_id) WHERE kind = 'home' AND superseded_at IS NULL;
CREATE INDEX thing_site ON thing (site_id, kind) WHERE site_id IS NOT NULL;
CREATE INDEX thing_type_idx ON thing (type);

CREATE TRIGGER thing_uid_fixed BEFORE UPDATE OF uid ON thing FOR EACH ROW WHEN (NEW.uid IS DISTINCT FROM OLD.uid) EXECUTE FUNCTION trg_uid_fixed();

CREATE FUNCTION trg_thing_identity_fixed() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'a thing keeps its kind and its home';
END $$;
CREATE TRIGGER thing_identity_fixed BEFORE UPDATE OF kind, site_id ON thing FOR EACH ROW
  WHEN (NEW.kind IS DISTINCT FROM OLD.kind OR NEW.site_id IS DISTINCT FROM OLD.site_id) EXECUTE FUNCTION trg_thing_identity_fixed();

-- A thing carries only the attributes its type lists (thing_type.attribute_keys).
CREATE FUNCTION trg_thing_attrs_allowed() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE bad text;
BEGIN
  -- (a non-object is refused by the column's CHECK, which runs after this trigger)
  SELECT k INTO bad FROM jsonb_object_keys(CASE WHEN jsonb_typeof(NEW.attrs) = 'object' THEN NEW.attrs ELSE '{}'::jsonb END) k
    WHERE NOT EXISTS (SELECT 1 FROM thing_type y WHERE y.type = NEW.type AND y.attribute_keys @> to_jsonb(k)) LIMIT 1;
  IF bad IS NOT NULL THEN RAISE EXCEPTION 'attribute % is not carried by type %', bad, NEW.type; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER thing_attrs_allowed BEFORE INSERT OR UPDATE OF attrs, type ON thing FOR EACH ROW EXECUTE FUNCTION trg_thing_attrs_allowed();

-- ───────────── attribute versions ─────────────
-- Every change of a thing's name or attributes is a version (record time: what was known when; valid time: from when it holds).
-- The thing row keeps the current values. The versions are written by the triggers below, never by code, and are append-only:
-- a version changes only by being superseded, and is deleted only inside a logged erasure.
CREATE TABLE thing_attr_version (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  thing_id bigint NOT NULL REFERENCES thing (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  site_id bigint REFERENCES site (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  name text NOT NULL,
  attrs jsonb NOT NULL,
  valid_from bigint,
  valid_to bigint,
  recorded_at bigint NOT NULL,
  superseded_at bigint,
  CONSTRAINT thing_attr_version_valid_window CHECK (valid_from IS NULL OR valid_to IS NULL OR valid_to > valid_from),
  CONSTRAINT thing_attr_version_record_window CHECK (superseded_at IS NULL OR superseded_at >= recorded_at),
  CONSTRAINT thing_attr_version_at UNIQUE (thing_id, recorded_at)
);
CREATE UNIQUE INDEX thing_attr_version_current ON thing_attr_version (thing_id) WHERE superseded_at IS NULL;
CREATE INDEX thing_attr_version_site ON thing_attr_version (site_id) WHERE site_id IS NOT NULL;

CREATE FUNCTION trg_thing_attr_version_on_insert() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO thing_attr_version (thing_id, site_id, name, attrs, valid_from, recorded_at)
    VALUES (NEW.id, NEW.site_id, NEW.name, NEW.attrs, COALESCE(NEW.valid_from, NEW.recorded_at / 1000), NEW.recorded_at);
  RETURN NULL;
END $$;
CREATE TRIGGER thing_attr_version_on_insert AFTER INSERT ON thing FOR EACH ROW EXECUTE FUNCTION trg_thing_attr_version_on_insert();

CREATE FUNCTION trg_thing_attr_version_on_update() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE at_ms bigint := GREATEST((extract(epoch FROM statement_timestamp()) * 1000)::bigint,
  (SELECT COALESCE(MAX(recorded_at), 0) + 1 FROM thing_attr_version WHERE thing_id = NEW.id));
BEGIN
  UPDATE thing_attr_version SET superseded_at = at_ms WHERE thing_id = NEW.id AND superseded_at IS NULL;
  INSERT INTO thing_attr_version (thing_id, site_id, name, attrs, valid_from, recorded_at) VALUES (NEW.id, NEW.site_id, NEW.name, NEW.attrs, at_ms / 1000, at_ms);
  RETURN NULL;
END $$;
CREATE TRIGGER thing_attr_version_on_update AFTER UPDATE OF name, attrs ON thing FOR EACH ROW
  WHEN (OLD.name IS DISTINCT FROM NEW.name OR OLD.attrs IS DISTINCT FROM NEW.attrs) EXECUTE FUNCTION trg_thing_attr_version_on_update();

CREATE FUNCTION trg_thing_attr_version_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF erasure_open() THEN RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END; END IF;
  IF TG_OP = 'DELETE' THEN RAISE EXCEPTION 'append-only: a thing version is never deleted (only by a logged erasure)'; END IF;
  IF OLD.superseded_at IS NOT NULL OR NEW.superseded_at IS NULL OR (to_jsonb(NEW) - 'superseded_at') <> (to_jsonb(OLD) - 'superseded_at') THEN
    RAISE EXCEPTION 'append-only: a thing version changes only by being superseded once (a new value is a new version)';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER thing_attr_version_append_only BEFORE UPDATE OR DELETE ON thing_attr_version FOR EACH ROW EXECUTE FUNCTION trg_thing_attr_version_append_only();

-- ───────────── relations ─────────────
-- A dated, typed edge between two things of one home (or shared context). valid_from is the next slot boundary after the
-- change (R13: a timeline never splits a slot); changed_at keeps the exact moment (seconds) for history.
CREATE TABLE thing_relation (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id bigint REFERENCES site (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,   -- set from the two things; none when both are shared context
  from_id bigint NOT NULL REFERENCES thing (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  from_port text CHECK (from_port <> ''),
  rel text NOT NULL CHECK (rel ~ '^[a-z][a-z0-9_]*$'),
  to_id bigint NOT NULL REFERENCES thing (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  to_port text CHECK (to_port <> ''),
  required bigint NOT NULL DEFAULT 1 CHECK (required IN (0, 1)),   -- does this member decide its group's data state (R8)
  valid_from bigint,
  valid_to bigint,
  changed_at bigint,
  recorded_at bigint NOT NULL DEFAULT (extract(epoch FROM clock_timestamp()) * 1000)::bigint,
  superseded_at bigint,
  CONSTRAINT thing_relation_not_self CHECK (from_id <> to_id),
  CONSTRAINT thing_relation_valid_window CHECK (valid_from IS NULL OR valid_to IS NULL OR valid_to > valid_from),
  CONSTRAINT thing_relation_snapped CHECK (changed_at IS NULL OR valid_from IS NULL OR valid_from >= changed_at),
  CONSTRAINT thing_relation_record_window CHECK (superseded_at IS NULL OR superseded_at >= recorded_at),
  CONSTRAINT relation_no_overlap EXCLUDE USING gist (from_id WITH =, to_id WITH =, rel WITH =, COALESCE(from_port, '') WITH =, COALESCE(to_port, '') WITH =,
    int8range(COALESCE(valid_from, -9000000000), COALESCE(valid_to, 9000000000)) WITH &&) WHERE (superseded_at IS NULL),
  CONSTRAINT located_in_one_place EXCLUDE USING gist (from_id WITH =, int8range(COALESCE(valid_from, -9000000000), COALESCE(valid_to, 9000000000)) WITH &&)
    WHERE (rel = 'located_in' AND superseded_at IS NULL)
);
CREATE INDEX thing_relation_from ON thing_relation (from_id, rel) WHERE superseded_at IS NULL;
CREATE INDEX thing_relation_to ON thing_relation (to_id, rel) WHERE superseded_at IS NULL;
CREATE INDEX thing_relation_site ON thing_relation (site_id) WHERE site_id IS NOT NULL;

-- A port of a type, or null.
CREATE FUNCTION thing_port(t text, p text) RETURNS jsonb LANGUAGE sql STABLE AS $$
  SELECT e FROM thing_type y, jsonb_array_elements(y.ports) e WHERE y.type = t AND e->>'name' = p
$$;

CREATE FUNCTION trg_thing_relation_checks() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE a thing%ROWTYPE; b thing%ROWTYPE; r relation_rule%ROWTYPE; pa jsonb; pb jsonb; home bigint;
BEGIN
  SELECT * INTO a FROM thing WHERE id = NEW.from_id;
  SELECT * INTO b FROM thing WHERE id = NEW.to_id;
  IF a.site_id IS NOT NULL AND b.site_id IS NOT NULL AND a.site_id <> b.site_id THEN
    RAISE EXCEPTION 'a relation joins things of one home, or shared context';
  END IF;
  home := COALESCE(a.site_id, b.site_id);
  IF TG_OP = 'INSERT' AND NEW.site_id IS NULL THEN NEW.site_id := home; END IF;
  IF NEW.site_id IS DISTINCT FROM home THEN RAISE EXCEPTION 'relation home differs from the home of its things'; END IF;

  SELECT * INTO r FROM relation_rule x
    WHERE x.rel = NEW.rel AND x.from_kind = a.kind AND (x.from_type IS NULL OR x.from_type = a.type)
      AND x.to_kind = b.kind AND (x.to_type IS NULL OR x.to_type = b.type)
    ORDER BY (x.from_type IS NOT NULL)::int + (x.to_type IS NOT NULL)::int DESC, x.id LIMIT 1;
  IF NOT FOUND THEN RAISE EXCEPTION 'no % rule allows a % to a %', NEW.rel, a.type, b.type; END IF;

  IF r.from_ports = 'none' AND NEW.from_port IS NOT NULL THEN RAISE EXCEPTION 'a % relation takes no port on its from side', NEW.rel; END IF;
  IF r.to_ports = 'none' AND NEW.to_port IS NOT NULL THEN RAISE EXCEPTION 'a % relation takes no port on its to side', NEW.rel; END IF;
  IF r.from_ports = 'required' AND NEW.from_port IS NULL THEN RAISE EXCEPTION 'a % relation needs a port on its from side', NEW.rel; END IF;
  IF r.to_ports = 'required' AND NEW.to_port IS NULL THEN RAISE EXCEPTION 'a % relation needs a port on its to side', NEW.rel; END IF;
  IF NEW.from_port IS NOT NULL THEN
    pa := thing_port(a.type, NEW.from_port);
    IF pa IS NULL THEN RAISE EXCEPTION 'type % has no port %', a.type, NEW.from_port; END IF;
    IF r.flow = 1 AND pa->>'dir' = 'in' THEN RAISE EXCEPTION 'port % of type % only receives', NEW.from_port, a.type; END IF;
  END IF;
  IF NEW.to_port IS NOT NULL THEN
    pb := thing_port(b.type, NEW.to_port);
    IF pb IS NULL THEN RAISE EXCEPTION 'type % has no port %', b.type, NEW.to_port; END IF;
    IF r.flow = 1 AND pb->>'dir' = 'out' THEN RAISE EXCEPTION 'port % of type % only sends', NEW.to_port, b.type; END IF;
  END IF;
  IF r.flow = 1 AND pa IS NOT NULL AND pb IS NOT NULL AND pa->>'medium' <> pb->>'medium' THEN
    RAISE EXCEPTION 'ports % and % carry different media (% and %)', NEW.from_port, NEW.to_port, pa->>'medium', pb->>'medium';
  END IF;
  IF r.same_type = 1 AND a.type <> b.type THEN RAISE EXCEPTION 'a % relation joins things of the same type', NEW.rel; END IF;

  -- No cycle: walk the current relations of this kind that overlap this one, from its target; reaching its source closes a loop.
  -- (a window that ends before it starts is refused by the table's CHECK, which runs after this trigger)
  IF r.acyclic = 1 AND NEW.superseded_at IS NULL AND COALESCE(NEW.valid_from, -9000000000) < COALESCE(NEW.valid_to, 9000000000) AND EXISTS (
    WITH RECURSIVE walk(id) AS (
      SELECT NEW.to_id
      UNION
      SELECT x.to_id FROM thing_relation x JOIN walk w ON x.from_id = w.id
        WHERE x.rel = NEW.rel AND x.superseded_at IS NULL AND x.id IS DISTINCT FROM NEW.id
          AND int8range(COALESCE(x.valid_from, -9000000000), COALESCE(x.valid_to, 9000000000)) && int8range(COALESCE(NEW.valid_from, -9000000000), COALESCE(NEW.valid_to, 9000000000))
    ) SELECT 1 FROM walk WHERE id = NEW.from_id) THEN
    RAISE EXCEPTION 'a % relation cannot form a cycle', NEW.rel;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER thing_relation_checks BEFORE INSERT OR UPDATE OF from_id, to_id, rel, from_port, to_port, site_id, valid_from, valid_to ON thing_relation
  FOR EACH ROW EXECUTE FUNCTION trg_thing_relation_checks();
