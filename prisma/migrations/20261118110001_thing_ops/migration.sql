-- Replace, merge and split (plan Phase 1.8, fix list R2). A merge keeps both things: the one that lost is superseded and points at
-- the one it was merged into, so the uid a hub still sends for it resolves to the survivor and its history stays readable. Each
-- operation is written down in thing_op (what, which things, why, what moved and what could not).

-- A thing's own span of life (valid_from, valid_to) is part of what is known about it: every change of it is a version too, so the
-- graph "as known at" a moment shows a device in service that was retired later. (life_from / life_to; the version's own valid_from
-- stays the time of the change.)
ALTER TABLE thing_attr_version ADD COLUMN life_from bigint, ADD COLUMN life_to bigint;

CREATE OR REPLACE FUNCTION trg_thing_attr_version_on_insert() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO thing_attr_version (thing_id, site_id, name, attrs, valid_from, life_from, life_to, recorded_at)
    VALUES (NEW.id, NEW.site_id, NEW.name, NEW.attrs, COALESCE(NEW.valid_from, NEW.recorded_at / 1000), NEW.valid_from, NEW.valid_to, NEW.recorded_at);
  RETURN NULL;
END $$;

CREATE OR REPLACE FUNCTION trg_thing_attr_version_on_update() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE at_ms bigint := GREATEST((extract(epoch FROM statement_timestamp()) * 1000)::bigint,
  (SELECT COALESCE(MAX(recorded_at), 0) + 1 FROM thing_attr_version WHERE thing_id = NEW.id));
BEGIN
  UPDATE thing_attr_version SET superseded_at = at_ms WHERE thing_id = NEW.id AND superseded_at IS NULL;
  INSERT INTO thing_attr_version (thing_id, site_id, name, attrs, valid_from, life_from, life_to, recorded_at)
    VALUES (NEW.id, NEW.site_id, NEW.name, NEW.attrs, at_ms / 1000, NEW.valid_from, NEW.valid_to, at_ms);
  RETURN NULL;
END $$;
DROP TRIGGER thing_attr_version_on_update ON thing;
CREATE TRIGGER thing_attr_version_on_update AFTER UPDATE OF name, attrs, valid_from, valid_to ON thing FOR EACH ROW
  WHEN (OLD.name IS DISTINCT FROM NEW.name OR OLD.attrs IS DISTINCT FROM NEW.attrs OR OLD.valid_from IS DISTINCT FROM NEW.valid_from OR OLD.valid_to IS DISTINCT FROM NEW.valid_to)
  EXECUTE FUNCTION trg_thing_attr_version_on_update();

ALTER TABLE thing ADD COLUMN merged_into bigint REFERENCES thing (id) DEFERRABLE INITIALLY IMMEDIATE;
ALTER TABLE thing ADD CONSTRAINT thing_merged_is_superseded CHECK (merged_into IS NULL OR (superseded_at IS NOT NULL AND merged_into <> id));
CREATE INDEX thing_merged_into_idx ON thing (merged_into) WHERE merged_into IS NOT NULL;

-- A thing is merged once, into a live thing of its own home and kind. (The CHECK above ties merged_into to superseded_at.)
CREATE FUNCTION trg_thing_merge_checks() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE w thing%ROWTYPE;
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.merged_into IS NOT NULL THEN RAISE EXCEPTION 'a thing is merged by updating a live thing, not created merged'; END IF;
    RETURN NEW;
  END IF;
  IF NEW.merged_into IS NOT DISTINCT FROM OLD.merged_into THEN RETURN NEW; END IF;
  IF OLD.merged_into IS NOT NULL THEN RAISE EXCEPTION 'a merged thing stays merged'; END IF;
  SELECT * INTO w FROM thing WHERE id = NEW.merged_into;
  IF w.site_id IS DISTINCT FROM NEW.site_id OR w.kind <> NEW.kind THEN RAISE EXCEPTION 'a thing merges into a thing of its own home and kind'; END IF;
  IF w.merged_into IS NOT NULL OR w.superseded_at IS NOT NULL THEN RAISE EXCEPTION 'a thing merges into a live thing'; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER thing_merge_checks BEFORE INSERT OR UPDATE OF merged_into ON thing FOR EACH ROW EXECUTE FUNCTION trg_thing_merge_checks();

-- A merged thing takes no new relation: what it had was carried over to the thing it was merged into.
CREATE FUNCTION trg_thing_relation_alive() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM thing WHERE id IN (NEW.from_id, NEW.to_id) AND merged_into IS NOT NULL) THEN
    RAISE EXCEPTION 'a merged thing takes no new relation (use the thing it was merged into)';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER thing_relation_alive BEFORE INSERT OR UPDATE OF from_id, to_id, superseded_at ON thing_relation
  FOR EACH ROW WHEN (NEW.superseded_at IS NULL) EXECUTE FUNCTION trg_thing_relation_alive();

-- What was done to the graph by hand: one row per replace, merge or split.
--   replace  thing_id is the old thing, other_id the new one
--   merge    thing_id is the thing that lost, other_id the thing it was merged into
--   split    thing_id is the thing that was split, other_id the new thing made from it
CREATE TABLE thing_op (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id bigint REFERENCES site (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,   -- the home; none for shared context
  op text NOT NULL CHECK (op IN ('replace', 'merge', 'split')),
  thing_id bigint NOT NULL REFERENCES thing (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  other_id bigint NOT NULL REFERENCES thing (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  effective_at bigint,                  -- s: from when the operation holds in valid time (a slot boundary), null when it holds from the thing's start
  reason text NOT NULL CHECK (length(btrim(reason)) > 0),
  detail jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(detail) = 'object'),   -- what moved, what was already covered, what could not move
  recorded_at bigint NOT NULL DEFAULT (extract(epoch FROM clock_timestamp()) * 1000)::bigint,
  CONSTRAINT thing_op_two_things CHECK (thing_id <> other_id)
);
CREATE INDEX thing_op_thing ON thing_op (thing_id);
CREATE INDEX thing_op_other ON thing_op (other_id);
CREATE INDEX thing_op_site ON thing_op (site_id) WHERE site_id IS NOT NULL;
