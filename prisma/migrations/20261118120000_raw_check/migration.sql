-- The raw-file check (plan phase 1.7): what each run found, and the latest result for each receipt.
-- raw_check_run is a log: one row per run for the whole store (site_id NULL) and one per home that had receipts in the run.
-- raw_payload_check is working state: when each receipt was last opened and hashed, and what came of it. The next run takes
-- the receipts checked longest ago (never-checked first), so a store is covered in turn whatever the server's uptime, and a
-- home's health shows its receipts' latest known state, not only the state in the last run.
-- raw_payload itself is append-only, so the check time cannot live on it.
CREATE TABLE raw_check_run (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id bigint REFERENCES site(id) ON DELETE CASCADE,   -- NULL: the whole run
  ran_at bigint NOT NULL,                                 -- unix seconds
  trigger text NOT NULL CHECK (trigger IN ('start', 'timer', 'cli')),
  checked integer NOT NULL CHECK (checked >= 0),
  ok integer NOT NULL CHECK (ok >= 0),
  mismatch integer NOT NULL CHECK (mismatch >= 0),
  corrupt integer NOT NULL CHECK (corrupt >= 0),
  missing integer NOT NULL CHECK (missing >= 0),
  unreadable integer NOT NULL CHECK (unreadable >= 0),
  erased integer NOT NULL CHECK (erased >= 0),
  unsealed integer NOT NULL CHECK (unsealed >= 0),
  bytes bigint NOT NULL CHECK (bytes >= 0),
  ms integer NOT NULL CHECK (ms >= 0)
);
CREATE INDEX raw_check_run_site ON raw_check_run (site_id, id DESC);

-- A log row records what a run found; it is never edited (a home's rows leave with the home, by the foreign key).
CREATE FUNCTION trg_raw_check_run_fixed() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'a raw check run is a log row and never changes';
END $$;
CREATE TRIGGER raw_check_run_fixed BEFORE UPDATE ON raw_check_run FOR EACH ROW EXECUTE FUNCTION trg_raw_check_run_fixed();

CREATE TABLE raw_payload_check (
  payload_id bigint PRIMARY KEY REFERENCES raw_payload(id) ON DELETE CASCADE,
  site_id bigint REFERENCES site(id) ON DELETE CASCADE,   -- the receipt's home when it was checked
  checked_at bigint NOT NULL,                             -- unix seconds
  state text NOT NULL CHECK (state IN ('ok', 'mismatch', 'corrupt', 'missing', 'unreadable', 'erased', 'unsealed'))
);
CREATE INDEX raw_payload_check_oldest ON raw_payload_check (checked_at, payload_id);
CREATE INDEX raw_payload_check_problem ON raw_payload_check (site_id) WHERE state NOT IN ('ok', 'erased');
