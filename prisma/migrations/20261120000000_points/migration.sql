-- ───────────── a point for every (thing, metric) a series is about ─────────────
INSERT INTO point (home_id, thing_id, key, metric_id, class, access)
  SELECT DISTINCT t.home_id, t.id, m.code, se.metric_id, metric_point_class(se.metric_id), metric_point_access(se.metric_id)
    FROM series se JOIN metric m ON m.id = se.metric_id
    JOIN thing t ON t.id = CASE se.subject_kind WHEN 'region' THEN (SELECT x.id FROM thing x WHERE x.kind = 'context' AND x.name = se.subject_id ORDER BY x.id LIMIT 1) ELSE se.subject_id::bigint END;

ALTER TABLE series ADD COLUMN point_id bigint;   -- (subject_kind and subject_id are read below, then derived from the point)
UPDATE series se SET point_id = p.id FROM point p, metric m
 WHERE m.id = se.metric_id AND p.metric_id = se.metric_id AND p.key = m.code AND p.superseded_at IS NULL
   AND p.thing_id = CASE se.subject_kind WHEN 'region' THEN (SELECT x.id FROM thing x WHERE x.kind = 'context' AND x.name = se.subject_id ORDER BY x.id LIMIT 1) ELSE se.subject_id::bigint END;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM series WHERE point_id IS NULL) THEN RAISE EXCEPTION 'a series has no point: its subject is not a thing'; END IF;
END $$;

-- subject_kind and subject_id stay for now as columns the database derives from the point (a home's own series, or those of its plant
-- things that have no integration behind them: 'site'; a device's: 'device'; a shared region's: 'region'). They are what the
-- queries of the build, the pages and the explorer say today; Phase 2.7 moves those queries onto points and drops the two columns.
DROP TRIGGER series_home ON series;
DROP FUNCTION trg_series_home();
ALTER TABLE series DROP CONSTRAINT series_subject_kind_subject_id_metric_id_source_id_key;
ALTER TABLE series ALTER COLUMN point_id SET NOT NULL;
ALTER TABLE series ADD CONSTRAINT series_point_id_fkey FOREIGN KEY (point_id) REFERENCES point (id) DEFERRABLE INITIALLY IMMEDIATE;
ALTER TABLE series ADD CONSTRAINT series_point_metric_source_key UNIQUE (point_id, metric_id, source_id);
CREATE INDEX series_point ON series (point_id);
CREATE INDEX series_subject ON series (subject_kind, subject_id);

-- A series' home and subject follow its point: the home of the point's thing (none for a regional series, like its point); the
-- subject is the home for the home thing and for plant things no integration is behind, the thing for a device, the name for a region.
CREATE FUNCTION trg_series_point() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE t thing%ROWTYPE; plant boolean;
BEGIN
  SELECT th.* INTO t FROM point p JOIN thing th ON th.id = p.thing_id WHERE p.id = NEW.point_id;
  plant := EXISTS (SELECT 1 FROM device d WHERE d.id = t.id AND d.provider = 'thing');
  IF t.kind = 'home' OR plant THEN NEW.subject_kind := 'site'; NEW.subject_id := t.home_id::text;
  ELSIF t.kind = 'context' THEN NEW.subject_kind := 'region'; NEW.subject_id := t.name;
  ELSE NEW.subject_kind := 'device'; NEW.subject_id := t.id::text; END IF;
  IF TG_OP = 'INSERT' AND NEW.site_id IS NULL THEN NEW.site_id := t.home_id; END IF;
  IF NEW.site_id IS DISTINCT FROM t.home_id THEN RAISE EXCEPTION 'series home differs from the home of its point'; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER series_home BEFORE INSERT OR UPDATE OF point_id, site_id ON series FOR EACH ROW EXECUTE FUNCTION trg_series_point();
