-- Phase 2.1 and 2.2: capabilities, points, and series on points (docs/build/points.md).
--
-- A point is one measurable or settable aspect of a thing (a battery's state of charge, an inverter's power, a room's
-- temperature). A series is the feed of one source into a point: facts keep their series, a series now names its point where it
-- named a subject (a home, a device or a region) before. A home's own series sit on its home thing until Phase 2.5 moves them onto
-- the inverter, battery and PV things; a device's on its device thing (the same id); a region's on a shared context thing.

-- ───────────── capabilities: what a kind of thing can do (rows come from src/db/seed/capabilities.js) ─────────────
CREATE TABLE capability (
  code text PRIMARY KEY CHECK (code ~ '^[a-z][a-z0-9_]*$'),
  label text NOT NULL CHECK (length(label) > 0),
  -- [{ "key": "power", "class": "measurement", "access": "read", "metrics": { "pv_array": "solar_w", "*": "..." } }]
  points jsonb NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(points) = 'array'),
  actions jsonb NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(actions) = 'array'),
  description text
);

-- A thing type may only name capabilities that are registered.
CREATE FUNCTION trg_thing_type_capabilities() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE missing text := (SELECT c FROM jsonb_array_elements_text(NEW.capabilities) c WHERE NOT EXISTS (SELECT 1 FROM capability k WHERE k.code = c) LIMIT 1);
BEGIN
  IF missing IS NOT NULL THEN RAISE EXCEPTION 'a thing type names a capability that is not registered: %', missing; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER thing_type_capabilities_exist BEFORE INSERT OR UPDATE OF capabilities ON thing_type FOR EACH ROW EXECUTE FUNCTION trg_thing_type_capabilities();

-- What a metric is as a point: its class and whether the core may write it. One place for the rule, used by the backfill below and
-- by the library when it makes a point.
CREATE FUNCTION metric_point_class(m bigint) RETURNS text LANGUAGE sql STABLE AS $$
  SELECT CASE
    WHEN code LIKE 'event\_%' THEN 'event'
    WHEN code LIKE 'ctl\_%' THEN 'setpoint'
    WHEN code LIKE '%counter\_kwh' THEN 'total'
    WHEN unit = '0/1' THEN 'state'
    WHEN time_role = 'interval' AND aggregation = 'sum' THEN 'total'
    ELSE 'measurement' END
  FROM metric WHERE id = m
$$;
CREATE FUNCTION metric_point_access(m bigint) RETURNS text LANGUAGE sql STABLE AS $$
  SELECT CASE WHEN code LIKE 'ctl\_%' THEN 'readwrite' ELSE 'read' END FROM metric WHERE id = m
$$;

-- ───────────── points ─────────────
CREATE TABLE point (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid uuid NOT NULL DEFAULT uuidv7() UNIQUE,
  home_id bigint REFERENCES thing (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,   -- the thing's home; none for a point of shared context
  thing_id bigint NOT NULL REFERENCES thing (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  key text NOT NULL CHECK (key ~ '^[a-z][a-z0-9_]*$'),                    -- what it is on this thing ('power', 'soc'); a metric code until a capability names it
  capability text REFERENCES capability (code) DEFERRABLE INITIALLY IMMEDIATE,
  metric_id bigint NOT NULL REFERENCES metric (id) DEFERRABLE INITIALLY IMMEDIATE,
  class text NOT NULL CHECK (class IN ('measurement', 'total', 'state', 'setpoint', 'event')),
  access text NOT NULL DEFAULT 'read' CHECK (access IN ('read', 'write', 'readwrite')),
  safe_default jsonb,                                                      -- what the hub reverts to (writable points)
  valid_from bigint,
  valid_to bigint,
  recorded_at bigint NOT NULL DEFAULT (extract(epoch FROM clock_timestamp()) * 1000)::bigint,
  superseded_at bigint,
  CONSTRAINT point_uid_v7 CHECK (uuid_extract_version(uid) = 7),
  CONSTRAINT point_valid_window CHECK (valid_from IS NULL OR valid_to IS NULL OR valid_to > valid_from),
  CONSTRAINT point_record_window CHECK (superseded_at IS NULL OR superseded_at >= recorded_at)
);
CREATE UNIQUE INDEX point_one_current ON point (thing_id, key) WHERE superseded_at IS NULL;
CREATE INDEX point_home ON point (home_id) WHERE home_id IS NOT NULL;
CREATE INDEX point_metric ON point (metric_id);

CREATE TRIGGER point_uid_fixed BEFORE UPDATE OF uid ON point FOR EACH ROW WHEN (NEW.uid IS DISTINCT FROM OLD.uid) EXECUTE FUNCTION trg_uid_fixed();

-- A point belongs to its thing's home; what a point is on its thing (the thing, the key, the metric) never changes: a different
-- aspect is a different point, and a feed moves to another point by changing its series.
CREATE FUNCTION trg_point_home() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE home bigint := (SELECT t.home_id FROM thing t WHERE t.id = NEW.thing_id);
BEGIN
  IF TG_OP = 'INSERT' AND NEW.home_id IS NULL THEN NEW.home_id := home; END IF;
  IF NEW.home_id IS DISTINCT FROM home THEN RAISE EXCEPTION 'point home differs from the home of its thing'; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER point_home_matches BEFORE INSERT OR UPDATE OF thing_id, home_id ON point FOR EACH ROW EXECUTE FUNCTION trg_point_home();
CREATE FUNCTION trg_point_identity_fixed() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'a point''s thing, key and metric never change: make another point';
END $$;
CREATE TRIGGER point_identity_fixed BEFORE UPDATE OF thing_id, key, metric_id ON point FOR EACH ROW
  WHEN (NEW.thing_id IS DISTINCT FROM OLD.thing_id OR NEW.key IS DISTINCT FROM OLD.key OR NEW.metric_id IS DISTINCT FROM OLD.metric_id) EXECUTE FUNCTION trg_point_identity_fixed();

