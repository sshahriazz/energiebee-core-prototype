-- Phase 2.3: a channel becomes a point binding, and a thing is tied to the provider's name for it by a link (docs/build/points.md).
--
-- point_binding: how one source's external point (a field of a provider's answer, a topic of a hub) becomes the values of a point:
-- the same columns the channel had (scale, sign part, limits, counter, event, clock), plus the point it feeds.
-- thing_link: a thing and the provider's own reference for it (a serial, an MPAN, a hub's device id), with valid time, so a
-- discovered device is found again and never made twice. A device with an integration behind it has one (made with it).

-- ───────────── channel is point_binding ─────────────
ALTER TABLE channel RENAME TO point_binding;
ALTER INDEX ix_channel_site_source RENAME TO ix_point_binding_site_source;
ALTER TABLE point_binding RENAME CONSTRAINT channel_pkey TO point_binding_pkey;
ALTER TABLE point_binding RENAME CONSTRAINT channel_access_check TO point_binding_access_check;
ALTER TABLE point_binding RENAME CONSTRAINT channel_enum_values_check TO point_binding_enum_values_check;
ALTER TABLE point_binding RENAME CONSTRAINT channel_kind_check TO point_binding_kind_check;
ALTER TABLE point_binding RENAME CONSTRAINT channel_part_check TO point_binding_part_check;
ALTER TABLE point_binding RENAME CONSTRAINT channel_derived_metric_id_fkey TO point_binding_derived_metric_id_fkey;
ALTER TABLE point_binding RENAME CONSTRAINT channel_device_id_fkey TO point_binding_device_id_fkey;
ALTER TABLE point_binding RENAME CONSTRAINT channel_metric_id_fkey TO point_binding_metric_id_fkey;
ALTER TABLE point_binding RENAME CONSTRAINT channel_site_id_fkey TO point_binding_site_id_fkey;

ALTER TABLE point_binding ADD COLUMN point_id bigint;
-- the point each binding feeds: on the device thing, or on the home thing for a home's own binding (the metric's code is its key)
INSERT INTO point (home_id, thing_id, key, metric_id, class, access)
  SELECT DISTINCT t.home_id, t.id, m.code, pb.metric_id, metric_point_class(pb.metric_id), metric_point_access(pb.metric_id)
    FROM point_binding pb JOIN metric m ON m.id = pb.metric_id JOIN thing t ON t.id = COALESCE(pb.device_id, pb.site_id)
  ON CONFLICT (thing_id, key) WHERE superseded_at IS NULL DO NOTHING;
UPDATE point_binding pb SET point_id = p.id FROM point p
 WHERE p.thing_id = COALESCE(pb.device_id, pb.site_id) AND p.metric_id = pb.metric_id AND p.superseded_at IS NULL;
-- a source that may write a point makes the point writable
UPDATE point p SET access = 'readwrite' FROM point_binding pb WHERE pb.point_id = p.id AND pb.access = 'readwrite' AND p.access = 'read';
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM point_binding WHERE point_id IS NULL) THEN RAISE EXCEPTION 'a binding has no point'; END IF;
END $$;
ALTER TABLE point_binding ALTER COLUMN point_id SET NOT NULL;
ALTER TABLE point_binding ADD CONSTRAINT point_binding_point_id_fkey FOREIGN KEY (point_id) REFERENCES point (id) DEFERRABLE INITIALLY IMMEDIATE;
CREATE INDEX point_binding_point ON point_binding (point_id);

-- A binding is in the home of its point and for its metric.
CREATE FUNCTION trg_point_binding_point() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE p point%ROWTYPE;
BEGIN
  SELECT * INTO p FROM point WHERE id = NEW.point_id;
  IF NEW.site_id IS DISTINCT FROM p.home_id THEN RAISE EXCEPTION 'a point binding is in the home of its point'; END IF;
  IF NEW.metric_id IS DISTINCT FROM p.metric_id THEN RAISE EXCEPTION 'a point binding is for the metric of its point'; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER point_binding_matches_point BEFORE INSERT OR UPDATE OF point_id, site_id, metric_id ON point_binding FOR EACH ROW EXECUTE FUNCTION trg_point_binding_point();

-- ───────────── links ─────────────
CREATE TABLE thing_link (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid uuid NOT NULL DEFAULT uuidv7() UNIQUE,
  home_id bigint NOT NULL REFERENCES thing (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  thing_id bigint NOT NULL REFERENCES thing (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  kind text NOT NULL CHECK (kind IN ('cloud', 'hub', 'push', 'manual', 'synthetic')),
  provider text NOT NULL CHECK (length(provider) > 0),               -- the integration: sunsynk, octopus, a hub driver, push
  connection_id bigint REFERENCES connection (id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,   -- the home's connection, when there is one
  external_ref text NOT NULL CHECK (length(external_ref) > 0),       -- the provider's name for the thing: a serial, an MPAN, a hub's device id
  valid_from bigint,
  valid_to bigint,
  recorded_at bigint NOT NULL DEFAULT (extract(epoch FROM clock_timestamp()) * 1000)::bigint,
  superseded_at bigint,
  CONSTRAINT thing_link_uid_v7 CHECK (uuid_extract_version(uid) = 7),
  CONSTRAINT thing_link_valid_window CHECK (valid_from IS NULL OR valid_to IS NULL OR valid_to > valid_from),
  CONSTRAINT thing_link_record_window CHECK (superseded_at IS NULL OR superseded_at >= recorded_at)
);
-- the provider's name points at one thing at a time in a home
CREATE UNIQUE INDEX thing_link_one_open ON thing_link (home_id, provider, external_ref) WHERE valid_to IS NULL AND superseded_at IS NULL;
CREATE INDEX thing_link_thing ON thing_link (thing_id);
CREATE TRIGGER thing_link_uid_fixed BEFORE UPDATE OF uid ON thing_link FOR EACH ROW WHEN (NEW.uid IS DISTINCT FROM OLD.uid) EXECUTE FUNCTION trg_uid_fixed();

-- A link is in the home of its thing (a thing of shared context has no link).
CREATE FUNCTION trg_thing_link_home() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE home bigint := (SELECT t.home_id FROM thing t WHERE t.id = NEW.thing_id);
BEGIN
  IF NEW.home_id IS DISTINCT FROM home THEN RAISE EXCEPTION 'a link is in the home of its thing'; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER thing_link_home_matches BEFORE INSERT OR UPDATE OF thing_id, home_id ON thing_link FOR EACH ROW EXECUTE FUNCTION trg_thing_link_home();

-- What kind of link a provider's device has (the providers that bring no device of their own are entered by hand).
CREATE FUNCTION thing_link_kind(provider text) RETURNS text LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE WHEN provider = 'synthetic' THEN 'synthetic' WHEN provider = 'push' THEN 'push' WHEN provider IN ('env', 'picker', 'tounify') THEN 'manual' ELSE 'cloud' END
$$;

-- A device row with an integration behind it is a link of its device thing, made with it and ended with it.
INSERT INTO thing_link (home_id, thing_id, kind, provider, connection_id, external_ref, valid_from, valid_to, recorded_at)
  SELECT d.site_id, d.id, thing_link_kind(d.provider), d.provider, c.id, d.external_ref, d.recorded_at / 1000, CASE WHEN d.retired_at IS NULL THEN NULL ELSE GREATEST(d.retired_at / 1000, COALESCE(d.recorded_at, 0) / 1000 + 1) END, COALESCE(d.recorded_at, 0)
    FROM device d LEFT JOIN connection c ON c.site_id = d.site_id AND c.provider = d.provider
   WHERE d.provider <> 'thing' ORDER BY d.id;
CREATE FUNCTION trg_device_make_link() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.provider <> 'thing' THEN
    INSERT INTO thing_link (home_id, thing_id, kind, provider, connection_id, external_ref, valid_from, recorded_at)
      SELECT NEW.site_id, NEW.id, thing_link_kind(NEW.provider), NEW.provider, (SELECT c.id FROM connection c WHERE c.site_id = NEW.site_id AND c.provider = NEW.provider LIMIT 1),
             NEW.external_ref, NEW.recorded_at / 1000, COALESCE(NEW.recorded_at, (extract(epoch FROM clock_timestamp()) * 1000)::bigint);
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER device_make_link AFTER INSERT ON device FOR EACH ROW EXECUTE FUNCTION trg_device_make_link();
CREATE FUNCTION trg_device_end_link() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  UPDATE thing_link SET valid_to = GREATEST(NEW.retired_at / 1000, COALESCE(valid_from, 0) + 1) WHERE thing_id = NEW.id AND valid_to IS NULL AND superseded_at IS NULL;
  RETURN NULL;
END $$;
CREATE TRIGGER device_end_link AFTER UPDATE OF retired_at ON device FOR EACH ROW WHEN (NEW.retired_at IS NOT NULL AND OLD.retired_at IS NULL) EXECUTE FUNCTION trg_device_end_link();
