-- Phase 4: controls on every thing (docs/build/controls.md).
--
-- control_request: somebody (the owner, a schedule, the optimiser, a safety rule) asks a thing to do something for a while. The highest
-- current request wins and becomes the command; when it expires a lower one returns. A request never changes once made: it is cancelled
-- or it expires. A change the owner made outside EnergieBee (the manufacturer's app) is a request too, marked external.
CREATE TABLE control_request (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid uuid NOT NULL DEFAULT uuidv7() UNIQUE,
  home_id bigint NOT NULL REFERENCES thing (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  thing_id bigint NOT NULL REFERENCES thing (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  capability text NOT NULL REFERENCES capability (code) DEFERRABLE INITIALLY IMMEDIATE,
  action text NOT NULL CHECK (action ~ '^[a-z][a-z0-9_]*$'),
  desired jsonb NOT NULL CHECK (jsonb_typeof(desired) = 'object'),        -- the state beyond the action (a target, a rate, a window)
  priority text NOT NULL CHECK (priority IN ('safety', 'manual', 'schedule', 'optimiser')),
  valid_from bigint NOT NULL,                                             -- s
  valid_until bigint NOT NULL,
  source text NOT NULL CHECK (length(btrim(source)) > 0),                 -- who asked: user:3, scene:7, optimiser, external
  note text,
  external bigint NOT NULL DEFAULT 0 CHECK (external IN (0, 1)),          -- a change made outside EnergieBee: nothing is sent for it, and it is not reverted before it expires
  group_uid uuid,                                                         -- the requests of one command on a room or a system
  created_at bigint NOT NULL,                                             -- ms
  cancelled_at bigint,
  CONSTRAINT control_request_window CHECK (valid_until > valid_from)
);
CREATE INDEX control_request_open ON control_request (thing_id, capability) WHERE cancelled_at IS NULL;
CREATE INDEX control_request_group ON control_request (group_uid) WHERE group_uid IS NOT NULL;
CREATE TRIGGER control_request_uid_fixed BEFORE UPDATE OF uid ON control_request FOR EACH ROW WHEN (NEW.uid IS DISTINCT FROM OLD.uid) EXECUTE FUNCTION trg_uid_fixed();

CREATE FUNCTION trg_control_request_home() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE home bigint := (SELECT t.home_id FROM thing t WHERE t.id = NEW.thing_id);
BEGIN
  IF NEW.home_id IS DISTINCT FROM home THEN RAISE EXCEPTION 'a control request is in the home of its thing'; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER control_request_home_matches BEFORE INSERT ON control_request FOR EACH ROW EXECUTE FUNCTION trg_control_request_home();

-- What was asked is never changed: a request is cancelled (once) or it runs out.
CREATE FUNCTION trg_control_request_fixed() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.cancelled_at IS NOT NULL THEN RAISE EXCEPTION 'a cancelled control request stays cancelled'; END IF;
  IF (NEW.home_id, NEW.thing_id, NEW.capability, NEW.action, NEW.desired, NEW.priority, NEW.valid_from, NEW.valid_until, NEW.source, NEW.note, NEW.external, NEW.group_uid, NEW.created_at)
     IS DISTINCT FROM (OLD.home_id, OLD.thing_id, OLD.capability, OLD.action, OLD.desired, OLD.priority, OLD.valid_from, OLD.valid_until, OLD.source, OLD.note, OLD.external, OLD.group_uid, OLD.created_at) THEN
    RAISE EXCEPTION 'a control request never changes: cancel it and ask again';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER control_request_fixed BEFORE UPDATE ON control_request FOR EACH ROW EXECUTE FUNCTION trg_control_request_fixed();

-- The command a request became.
ALTER TABLE command ADD COLUMN request_id bigint REFERENCES control_request (id) DEFERRABLE INITIALLY IMMEDIATE;

-- A limit on a place applies to everything in it: 'each' member is held to it, 'sum' says the members' values together may not pass it
-- (a garage's chargers: 32 A across them).
ALTER TABLE control_limit ADD COLUMN aggregate text NOT NULL DEFAULT 'each' CHECK (aggregate IN ('each', 'sum'));

-- Scenes: named sets of desired states, and when they are asked for. Working state: what was sent is kept in control_request and command.
CREATE TABLE scene (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid uuid NOT NULL DEFAULT uuidv7() UNIQUE,
  home_id bigint NOT NULL REFERENCES thing (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  name text NOT NULL CHECK (length(btrim(name)) > 0),
  created_at bigint NOT NULL,
  updated_at bigint NOT NULL,
  UNIQUE (home_id, name)
);
CREATE TRIGGER scene_uid_fixed BEFORE UPDATE OF uid ON scene FOR EACH ROW WHEN (NEW.uid IS DISTINCT FROM OLD.uid) EXECUTE FUNCTION trg_uid_fixed();
CREATE TABLE scene_item (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scene_id bigint NOT NULL REFERENCES scene (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  thing_id bigint NOT NULL REFERENCES thing (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,   -- a device, or a place (every capable member)
  capability text NOT NULL REFERENCES capability (code) DEFERRABLE INITIALLY IMMEDIATE,
  action text NOT NULL CHECK (action ~ '^[a-z][a-z0-9_]*$'),
  desired jsonb NOT NULL CHECK (jsonb_typeof(desired) = 'object'),
  UNIQUE (scene_id, thing_id, capability)
);
CREATE TABLE scene_schedule (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scene_id bigint NOT NULL REFERENCES scene (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  weekdays text NOT NULL CHECK (weekdays ~ '^[1-7](,[1-7])*$'),          -- ISO: 1 Monday to 7 Sunday
  from_min bigint NOT NULL CHECK (from_min >= 0 AND from_min < 1440),    -- local minute of the day the scene starts
  until_min bigint NOT NULL CHECK (until_min > 0 AND until_min <= 1440), -- and ends (a window never crosses midnight: two schedules do)
  CONSTRAINT scene_schedule_window CHECK (until_min > from_min)
);

-- 4.1: actions belong to capabilities. A device is confirmed for an action when its type's capabilities allow it, or (as before) its kind lists it
-- in device_action; the action is no longer refused for a kind (a smart plug's on and off) the older table never listed.
CREATE OR REPLACE FUNCTION trg_device_capability_known_action() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM device d JOIN device_action a ON a.device_kind = d.kind AND a.action = NEW.action WHERE d.id = NEW.device_id)
     AND NOT EXISTS (SELECT 1 FROM thing t JOIN thing_type ty ON ty.type = t.type JOIN capability c ON ty.capabilities ? c.code WHERE t.id = NEW.device_id AND c.actions ? NEW.action) THEN
    RAISE EXCEPTION 'device_capability: action not defined in device_action for this device kind';
  END IF;
  RETURN NEW;
END $$;
CREATE OR REPLACE FUNCTION trg_device_capability_known_action_update() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM device d JOIN device_action a ON a.device_kind = d.kind AND a.action = NEW.action WHERE d.id = NEW.device_id)
     AND NOT EXISTS (SELECT 1 FROM thing t JOIN thing_type ty ON ty.type = t.type JOIN capability c ON ty.capabilities ? c.code WHERE t.id = NEW.device_id AND c.actions ? NEW.action) THEN
    RAISE EXCEPTION 'device_capability: action not defined in device_action for this device kind';
  END IF;
  RETURN NEW;
END $$;
