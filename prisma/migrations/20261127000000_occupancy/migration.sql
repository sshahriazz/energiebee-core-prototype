-- A home changes hands (R21) and a person asks to be erased (R14): the home's history (things, facts, timelines) belongs to the home; who lived
-- there, and what is personal to them (logins, supplier agreements, requests, the raw answers of their supplier account), belongs to an occupancy.
-- An occupancy is one person's time at a home. A handover ends one and opens the next; the new one reads the home's history from its own
-- start only, unless the previous occupant shared more (sees_from). Raw files of a personal source are sealed with the occupancy's own key,
-- so destroying the key erases them even where a copy survives (crypto-shredding per occupancy, as the home key does for a home).
CREATE TABLE occupancy (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid         uuid   NOT NULL DEFAULT uuidv7() UNIQUE,
  home_id     bigint NOT NULL REFERENCES site (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  user_id     bigint REFERENCES app_user (id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  role        text   NOT NULL DEFAULT 'owner' CHECK (role IN ('owner', 'occupant')),
  valid_from  bigint,
  valid_to    bigint,
  sees_from   bigint,
  erased_at   bigint,
  recorded_at bigint NOT NULL DEFAULT (EXTRACT(epoch FROM clock_timestamp()) * 1000)::bigint,
  CHECK (valid_to IS NULL OR valid_from IS NULL OR valid_to > valid_from),
  CHECK (erased_at IS NULL OR user_id IS NULL)
);
CREATE INDEX occupancy_home ON occupancy (home_id, valid_from);
CREATE INDEX occupancy_user ON occupancy (user_id) WHERE user_id IS NOT NULL;
CREATE UNIQUE INDEX occupancy_one_open ON occupancy (home_id, user_id) WHERE valid_to IS NULL AND user_id IS NOT NULL;
COMMENT ON COLUMN occupancy.valid_from IS 'epoch s; null: since the home''s history began';
COMMENT ON COLUMN occupancy.sees_from IS 'epoch s; the earliest moment of the home''s history this occupant may read (null: all of it)';

CREATE TABLE occupancy_key (
  occupancy_id bigint PRIMARY KEY REFERENCES occupancy (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  key          bytea  NOT NULL CHECK (length(key) = 32),
  created_at   bigint NOT NULL
);

ALTER TABLE raw_payload ADD COLUMN occupancy_id bigint REFERENCES occupancy (id) DEFERRABLE INITIALLY IMMEDIATE;
CREATE INDEX raw_payload_occupancy ON raw_payload (occupancy_id) WHERE occupancy_id IS NOT NULL;

ALTER TABLE erasure_log DROP CONSTRAINT erasure_log_kind_check;
ALTER TABLE erasure_log ADD CONSTRAINT erasure_log_kind_check CHECK (kind IN ('home', 'retention', 'anonymise', 'synthetic', 'person', 'handover'));
