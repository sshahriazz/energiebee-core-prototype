-- Three real-world gaps of the design review, built together because each is one small table:
--   R6   fusion: a feed of a total point can be its 'shape' (where in the day the energy went) or its 'total' (how much there was); the point's
--        slots take the shape scaled to the total, and flag a disagreement beyond the tolerance (src/core/point-slots.js)
--   R24  a thing moves to another home: the old thing ends in the old home, a successor begins in the new one, and thing_rehome ties the two
--   R20  a thing shared by several homes: thing_share gives each home a dated share of it (src/core/shared.js)
ALTER TABLE series ADD COLUMN fusion_role text CHECK (fusion_role IN ('shape', 'total'));
ALTER TABLE point ADD COLUMN fusion_tolerance double precision CHECK (fusion_tolerance IS NULL OR (fusion_tolerance > 0 AND fusion_tolerance < 1));

CREATE TABLE thing_rehome (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  from_thing   bigint NOT NULL REFERENCES thing (id) DEFERRABLE INITIALLY IMMEDIATE,
  to_thing     bigint NOT NULL REFERENCES thing (id) DEFERRABLE INITIALLY IMMEDIATE,
  from_home    bigint NOT NULL,
  to_home      bigint NOT NULL,
  effective_at bigint NOT NULL,
  reason       text   NOT NULL CHECK (length(btrim(reason)) > 0),
  recorded_at  bigint NOT NULL DEFAULT (EXTRACT(epoch FROM clock_timestamp()) * 1000)::bigint,
  CHECK (from_home <> to_home AND from_thing <> to_thing)
);
CREATE UNIQUE INDEX thing_rehome_from ON thing_rehome (from_thing);
CREATE UNIQUE INDEX thing_rehome_to ON thing_rehome (to_thing);

CREATE TABLE thing_share (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  thing_id    bigint NOT NULL REFERENCES thing (id) DEFERRABLE INITIALLY IMMEDIATE,
  home_id     bigint NOT NULL REFERENCES site (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  share       double precision NOT NULL CHECK (share > 0 AND share <= 1),
  basis       text NOT NULL DEFAULT 'fixed' CHECK (basis IN ('fixed', 'submeter')),
  valid_from  bigint NOT NULL,
  valid_to    bigint,
  recorded_at bigint NOT NULL DEFAULT (EXTRACT(epoch FROM clock_timestamp()) * 1000)::bigint,
  superseded_at bigint,
  CHECK (valid_to IS NULL OR valid_to > valid_from)
);
CREATE INDEX thing_share_thing ON thing_share (thing_id, valid_from);
CREATE INDEX thing_share_home ON thing_share (home_id);
