// Sources that are named in the registry but have no integration yet.
export const UNCLAIMED_SOURCES = Object.freeze(['axle_vpp', 'heating_telemetry', 'weather_alerts']);

/** The manifest: every integration with its markets and licence (market_provider), its roles (registered steps) and its sources (source). */
export async function integrationManifest(d = db) {
  const rows = await d.prepare('SELECT adapter, role, market_code, owner, scope, needs_credentials, licence_confirmed, enabled, note FROM market_provider ORDER BY adapter, role, market_code').all();
  const sources = new Map((await d.prepare('SELECT code, name, traits FROM source').all()).map((s) => [s.code, s]));
  const registered = new Set(adapterCodes());
  return INTEGRATIONS.map((e) => {
    const mine = rows.filter((r) => r.adapter === e.code);
    return {
      ...e,
      implemented: registered.has(e.code),
      roles: [...new Set([...(adapterFor(e.code)?.roles ? Object.keys(adapterFor(e.code).roles) : []), ...mine.map((r) => r.role)])].sort(),
      markets: [...new Set(mine.map((r) => r.market_code))].sort(),
      needsCredentials: mine.some((r) => r.needs_credentials === 1),
      licenceConfirmed: mine.length ? mine.every((r) => r.licence_confirmed === 1) : null,
      owner: mine[0]?.owner ?? adapterFor(e.code)?.owner ?? 'core',
      sourceRows: e.sources.map((c) => (sources.has(c) ? { code: c, name: sources.get(c).name, traits: JSON.parse(sources.get(c).traits || '{}') } : { code: c, name: null, traits: {} })),
    };
  });
}

/** What does not add up: an adapter or a provider row with no entry, a source named but not in the registry, a source in two entries. */
export async function manifestProblems(d = db) {
  const out = [];
  const known = new Set(INTEGRATIONS.map((e) => e.code));
  for (const c of adapterCodes()) if (!known.has(c)) out.push(`adapter ${c} is registered but has no manifest entry`);
  for (const r of await d.prepare('SELECT DISTINCT adapter FROM market_provider').all()) if (!known.has(r.adapter)) out.push(`market_provider names ${r.adapter}, which has no manifest entry`);
  const registry = new Set((await d.prepare('SELECT code FROM source').all()).map((s) => s.code));
  const owner = new Map();
  for (const e of INTEGRATIONS) for (const s of e.sources) {
    // the sources of generated data, and two that are made when their adapter first runs, are not in the registry at start
    if (!registry.has(s) && e.access !== 'generated' && !['tariffscanner', 'tounify'].includes(s)) out.push(`${e.code}: source ${s} is not in the source registry`);
    if (owner.has(s)) out.push(`source ${s} is in both ${owner.get(s)} and ${e.code}`);
    owner.set(s, e.code);
  }
  for (const s of registry) if (!owner.has(s) && !UNCLAIMED_SOURCES.includes(s)) out.push(`source ${s} belongs to no integration`);
  return out;
}
