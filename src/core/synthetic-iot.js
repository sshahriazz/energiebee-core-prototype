// A synthetic IoT home: a smart plug, a heat pump, an EV charger, a battery and a temperature sensor whose every
// reading is GENERATED here, so the device architecture (channels, counters, events, roles, control read-back) can be
// seen working without a real device. Nothing in it is real data and everything says so: the home is a demo home
// (site.is_demo), every device has provider 'synthetic', every source code starts synthetic_ and its contract says
// the data is generated.
//
// The data goes in through the REAL path (ingestObservations), never by direct inserts, and the same step function
// makes the history and the "next period" of the simulate button, so what the page adds later is what the history
// would have contained. Deterministic: a value is a pure function of the time (a hash, no hidden random state), so tests
// are stable. The history ends LAG_S before "now": the devices show as stale until the page simulates the periods in
// between, and there is room for a few presses before the clock is reached.
