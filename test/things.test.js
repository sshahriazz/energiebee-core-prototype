await test('slot boundaries: the next boundary on the home\'s grid, a change on a boundary stays on it', () => {
  const b = (ts, o) => T.nextSlotBoundary(ts, o);
  assert.equal(b(at(14, 10), { slotS: 1800 }), at(14, 30));
  assert.equal(b(at(14, 30), { slotS: 1800 }), at(14, 30), 'exactly on a boundary');
  assert.equal(b(at(14, 30) + 1, { slotS: 1800 }), at(15));
  assert.equal(b(at(14, 10), { slotS: 900 }), at(14, 15));
  assert.equal(b(at(14, 10), { slotS: 3600 }), at(15));
  assert.equal(b(at(23, 50), { slotS: 1800 }), at(24), 'the last slot of the day ends at midnight');
  // Slots count elapsed time from local midnight, so a day that is not 24 hours long has fewer or more of them, and the last one ends on
  // the day's own midnight. Clocks go forward on 2027-03-28 in London (01:00 UTC): the day has 23 hours.
  const L = { timezone: 'Europe/London' };
  const spring = Date.UTC(2027, 2, 28) / 1000;   // local midnight
  assert.equal(b(spring + 3 * 3600 + 100, { slotS: 1800, ...L }), spring + 3 * 3600 + 1800);
  assert.equal(b(spring + 3600 + 600, { slotS: 3600, ...L }), spring + 7200, '02:10 BST is 1 h 10 into the day: the next hour is 03:00 BST, not 02:00 read off the wall clock');
  assert.equal(b(spring + 22 * 3600 + 40 * 60, { slotS: 3600, ...L }), spring + 23 * 3600, 'the last slot of a 23-hour day ends on its midnight');
  assert.equal(b(spring + 23 * 3600, { slotS: 900, ...L }), spring + 23 * 3600, 'which is itself a boundary');
  // Clocks go back on 2027-10-31 (01:00 UTC, 02:00 BST becomes 01:00 GMT): the day has 25 hours and 01:10 happens twice.
  const autumn = Date.UTC(2027, 9, 30, 23) / 1000;   // local midnight, BST
  for (const slotS of [900, 1800, 3600]) {
    const o = { slotS, ...L };
    const grid = (offset) => autumn + Math.ceil(offset / slotS) * slotS;   // slots counted from local midnight on the elapsed clock
    assert.equal(b(autumn + 4200, o), grid(4200), `00:10 UTC, the first 01:10 (${slotS} s)`);
    assert.equal(b(autumn + 7800, o), grid(7800), `01:10 UTC, the second 01:10, is a different moment (${slotS} s)`);
    assert.equal(b(autumn + 24 * 3600 + 50 * 60, o), autumn + 25 * 3600, `a change in the last slot of a 25-hour day ends on its midnight (${slotS} s)`);
    assert.equal(b(autumn + 25 * 3600 - slotS, o), autumn + 25 * 3600 - slotS, 'a change on a boundary stays on it');
  }
  // a zone whose hour starts at :30 UTC: an hourly grid anchored to local midnight is not on the epoch's hours
  const mid = Date.UTC(2027, 0, 14, 18, 30) / 1000;   // local midnight in Asia/Kolkata (UTC+5:30)
  assert.equal(b(mid + 600, { slotS: 3600, timezone: 'Asia/Kolkata' }), mid + 3600);
  assert.equal((mid + 3600) % 3600, 1800, 'which is half past in UTC');
  assert.throws(() => b(100, { slotS: 1234 }), /slot length/);
});

