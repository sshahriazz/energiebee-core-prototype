await test('one operation is one moment in record time: a read at its own stamp sees all of it, one just before sees none of it', async () => {
  const room = await mk('room', 'Stamp room');
  const dev = await mk('smart_plug', 'Stamp plug', { model: 'S1' }, { validFrom: at(0) });
  await T.relate({ from: dev.id, rel: 'located_in', to: room.id, at: at(0) });
  const out = await T.replaceThing(dev.id, { name: 'Stamp plug (new)', inherit: ['model'], reason: 'one moment', at: at(6) });
  const stamp = (await get('SELECT recorded_at FROM thing_op WHERE id = ?', out.op)).recorded_at;
  const rowsAt = await all('SELECT recorded_at FROM thing_attr_version WHERE thing_id = ANY(?::bigint[])', `{${out.old.id},${out.thing.id}}`);
  const stamps = [stamp, out.thing.recorded_at, ...(await all("SELECT recorded_at FROM thing_relation WHERE (from_id = ? OR to_id = ?) AND recorded_at >= ?", dev.id, out.thing.id, stamp)).map((x) => x.recorded_at)];
  assert.deepEqual([...new Set(stamps)], [stamp], 'the new thing and every relation it wrote carry the one stamp');
  assert.ok(rowsAt.some((x) => x.recorded_at === stamp), 'the new thing\'s first version carries it');
  const oldVersion = await get('SELECT recorded_at FROM thing_attr_version WHERE thing_id = ? AND superseded_at IS NULL', out.old.id);
  assert.equal(oldVersion.recorded_at, stamp, 'so does the old thing\'s retirement');
  const view = async (known) => {
    const g = await T.graph(A, { at: at(7), known });
    // the edges are read as relations: the graph leaves out an edge to a thing that is no node at that time, and the retired plug is not
    const edges = await T.relationsAt(A, { at: at(7), known, rels: ['located_in', 'replaces'] });
    return [names(g.nodes.filter((n) => n.name.startsWith('Stamp plug'))).sort(), edges.filter((e) => e.from_id === dev.id || e.from_id === out.thing.id || e.to_id === dev.id).map((e) => `${e.rel}:${e.from_id === dev.id ? 'old' : 'new'}`).sort()];
  };
  assert.deepEqual(await view(stamp - 1), [['Stamp plug'], ['located_in:old']], 'just before: the old plug, in its room');
  assert.deepEqual(await view(stamp), [['Stamp plug (new)'], ['located_in:new', 'replaces:new']], 'at the stamp: the whole replacement');
});

await test('walks stay in one home, and a dense feeds network is walked once per thing', async () => {
  const siteC = await site('Home C');
  await T.createThing({ siteId: siteC, type: 'house', name: 'Home C' });
  const tariff = await T.createThing({ type: 'tariff', name: 'Shared tariff', attrs: { provider: 'Acme' } });
  const mA = await mk('meter_import', 'Meter of A');
  const mC = await T.createThing({ siteId: siteC, type: 'meter_import', name: 'Meter of C' });
  for (const m of [mA, mC]) await T.relate({ from: m.id, rel: 'supplied_on', to: tariff.id, at: at(0) });
  assert.deepEqual(names(await T.reach(tariff.id, { siteId: A, rel: 'supplied_on', direction: 'in', at: at(1) })), ['Meter of A'], 'from shared context, only this home\'s meters');
  assert.deepEqual(names(await T.reach(tariff.id, { siteId: siteC, rel: 'supplied_on', direction: 'in', at: at(1) })), ['Meter of C']);
  await refused(() => T.reach(mC.id, { siteId: A, rel: 'supplied_on' }), /no thing .* in home/);
  await refused(() => T.tree(mC.id, { siteId: A }), /no thing .* in home/);
  await refused(() => T.thingHistory(tariff.id, { siteId: A }), /no thing .* in home/);
  await refused(() => T.placeChain(mA.id, {}), /give siteId/);
  // 18 layers of two meters, each feeding both of the next: the number of paths is 2^17, the number of things 36
  let layer = [await mk('meter_import', 'L0a'), await mk('meter_import', 'L0b')];
  const first = layer[0];
  for (let i = 1; i < 18; i++) {
    const next = [await mk('meter_import', `L${i}a`), await mk('meter_import', `L${i}b`)];
    for (const f of layer) for (const t of next) await T.relate({ from: f.id, fromPort: 'load', rel: 'feeds', to: t.id, toPort: 'grid', at: at(0) });
    layer = next;
  }
  const started = Date.now();
  const out = await T.reach(first.id, { siteId: A, at: at(1) });
  assert.equal(out.length, 34, 'every thing of the 17 layers after the first; the other first-layer meter feeds forward only');
  assert.equal(out.find((x) => x.name === 'L17b').depth, 17);
  assert.ok(Date.now() - started < 2000, `walked in ${Date.now() - started} ms`);
});

