await test('replace a device (case 1): the new thing takes the place in the graph from the boundary, timelines run on unbroken', async () => {
  const before = await T.graph(A, { at: at(11) });
  const edgesOf = (g, id) => g.edges.filter((e) => e.from_id === id || e.to_id === id).map((e) => `${e.rel}:${e.from_port ?? ''}>${e.to_port ?? ''}`).sort();
  const oldEdges = edgesOf(before, inverter.id);
  assert.ok(oldEdges.length >= 5, oldEdges.join(' '));
  await refused(() => T.replaceThing(inverter.id, { name: 'New inverter', at: at(12, 20) }), /needs a reason/);
  await refused(() => T.replaceThing(garage.id, { name: 'x', reason: 'r' }), /only a device is replaced/);
  const known = Date.now();
  await new Promise((r) => setTimeout(r, 5));
  const out = await T.replaceThing(inverter.uid, { name: 'New inverter', attrs: { manufacturer: 'New Co' }, inherit: ['manufacturer'], at: at(12, 20), reason: 'the old inverter failed' });
  assert.equal(out.boundary, at(12, 30));
  assert.deepEqual([out.thing.type, out.thing.valid_from, out.old.valid_to, out.thing.attrs], ['inverter', at(12, 30), at(12, 30), { manufacturer: 'New Co' }]);
  assert.notEqual(out.thing.uid, inverter.uid);
  const neu = out.thing;
  // before the boundary the old inverter is in the graph, from the boundary on the new one, on the same ports, with the same other ends
  const g1 = await T.graph(A, { at: at(12, 29) });
  const g2 = await T.graph(A, { at: at(12, 30) });
  assert.deepEqual(edgesOf(g1, inverter.id), oldEdges);
  assert.deepEqual(edgesOf(g1, neu.id), []);
  assert.deepEqual(edgesOf(g2, neu.id), oldEdges, 'the same edges on the same ports');
  assert.deepEqual(edgesOf(g2, inverter.id), []);
  assert.equal(g1.nodes.some((n) => n.id === neu.id), false);
  assert.equal(g2.nodes.some((n) => n.id === inverter.id), false, 'a retired thing is not in the graph after it left');
  // the flow: PV reaches the consumer unit through whichever inverter is there
  const flow = async (t) => names(await T.reach(pv.id, { at: t }));
  assert.deepEqual(await flow(at(12, 0)), ['Inverter', 'Battery', 'Consumer unit']);
  assert.deepEqual(await flow(at(13, 0)), ['New inverter', 'Battery', 'Consumer unit']);
  assert.deepEqual(names(await T.reach(supply.id, { at: at(13), direction: 'in' })).sort(), ['Battery', 'New inverter', 'PV']);
  assert.deepEqual(names(await T.placeChain(neu.id, { at: at(13) })), ['New inverter', 'Garage', 'Home A'], 'in the same place');
  assert.deepEqual(names(await T.placeChain(inverter.id, { at: at(12) })), ['Inverter', 'Garage', 'Home A']);
  // the replacement as recorded, and as known before it
  const rep = await T.relationsAt(A, { rels: ['replaces'], at: at(13) });
  assert.deepEqual(rep.map((e) => [e.from_id, e.to_id, e.valid_from]), [[neu.id, inverter.id, at(12, 30)]]);
  const old = await T.graph(A, { at: at(13), known });
  assert.equal(old.nodes.some((n) => n.id === neu.id), false, 'not yet known');
  assert.deepEqual(edgesOf(old, inverter.id), oldEdges, 'as known before, the old inverter was still in the graph at 13:00');
  const h = await T.thingHistory(neu.id);
  assert.deepEqual(h.ops.map((o) => [o.op, o.thing_id, o.other_id, o.effective_at, o.reason]), [['replace', inverter.id, neu.id, at(12, 30), 'the old inverter failed']]);
  await refused(() => T.replaceThing(inverter.id, { name: 'again', reason: 'r', at: at(14) }), /replaced already/);
  await refused(() => T.replaceThing(neu.id, { name: 'too early', reason: 'r', at: at(12, 0) }), /began at/);
  // the second replacement chains: new -> newer
  const third = await T.replaceThing(neu.id, { name: 'Newest inverter', reason: 'upgrade', at: at(20) });
  assert.deepEqual(names(await T.reach(pv.id, { at: at(21) })), ['Newest inverter', 'Battery', 'Consumer unit']);
  assert.deepEqual((await T.relationsAt(A, { rels: ['replaces'], at: at(21) })).map((e) => e.from_id).sort(), [neu.id, third.thing.id].sort());
});

