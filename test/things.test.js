await test('the operations are atomic: a refusal after the work was done leaves the graph as it was', async () => {
  const c = await mk('inverter', 'Atomic inverter', {}, { validFrom: at(0) });
  await T.relate({ from: c.id, rel: 'located_in', to: garage.id, at: at(0) });
  const count = async () => [(await get('SELECT COUNT(*) AS n FROM thing_relation')).n, (await get('SELECT COUNT(*) AS n FROM thing')).n];
  const twin = await mk('inverter', 'Twin');
  const before = await count();
  // the last statement of a replace writes its log row: make that refuse
  await db.exec(`CREATE FUNCTION refuse_op() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'log refused'; END $$;
    CREATE TRIGGER refuse_op BEFORE INSERT ON thing_op FOR EACH ROW EXECUTE FUNCTION refuse_op()`);
  await refused(() => T.replaceThing(c.id, { name: 'Bad', reason: 'r', at: at(5) }), /log refused/);
  await refused(() => T.mergeThings(c.id, twin.id, { reason: 'r' }), /log refused/);
  await db.exec('DROP TRIGGER refuse_op ON thing_op; DROP FUNCTION refuse_op()');
  const after = await count();
  assert.deepEqual(after, before, 'no relation and no replacement thing was left behind');
  assert.deepEqual([(await T.getThing(c.id)).valid_to, (await T.getThing(c.id)).merged_into], [null, null]);
});
