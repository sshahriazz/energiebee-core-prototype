await test('relate: a change takes effect at the next slot boundary and keeps the exact moment (case 21)', async () => {
  const r = await T.relate({ from: plug.id, rel: 'located_in', to: garage.id, at: at(8, 5) });
  assert.deepEqual([r.changed_at, r.valid_from, r.site_id], [at(8, 5), at(8, 30), A]);
  for (const [a, b] of [[floor, home], [kitchen, floor], [living, floor], [garage, home]]) await T.relate({ from: a.id, rel: 'located_in', to: b.id, at: at(0) });
  // the plug is moved from the garage to the kitchen at 14:10
  const m = await T.moveThing(plug.id, kitchen.uid, { at: at(14, 10) });
  assert.deepEqual([m.changedAt, m.boundary, m.from, m.relation.valid_from, m.relation.changed_at], [at(14, 10), at(14, 30), garage.id, at(14, 30), at(14, 10)]);
  const placeAt = async (t) => (await T.placeChain(plug.id, { at: t }))[1]?.name;
  assert.equal(await placeAt(at(14, 0)), 'Garage', 'the 14:00 slot counts in the garage');
  assert.equal(await placeAt(at(14, 29)), 'Garage');
  assert.equal(await placeAt(at(14, 30)), 'Kitchen', 'the 14:30 slot in the kitchen');
  assert.deepEqual(names(await T.placeChain(plug.id, { at: at(15) })), ['Kettle plug', 'Kitchen', 'Ground floor', 'Home A']);
  // the old placement ended at the boundary and is still there: in history, and as known before the move
  const rows = await all("SELECT to_id, valid_from, valid_to, superseded_at FROM thing_relation WHERE from_id = ? AND rel = 'located_in' ORDER BY id", plug.id);
  assert.deepEqual(rows.map((x) => [x.to_id, x.valid_from, x.valid_to, x.superseded_at !== null]), [[garage.id, at(8, 30), null, true], [garage.id, at(8, 30), at(14, 30), false], [kitchen.id, at(14, 30), null, false]]);
  const before = rows[0].superseded_at - 1;
  assert.equal((await T.placeChain(plug.id, { at: at(15), known: before }))[1].name, 'Garage', 'as known before the move, it stays in the garage');
  assert.deepEqual(names((await T.tree(kitchen.id, { at: at(15) })).children), ['Kettle plug']);
  assert.deepEqual(names((await T.tree(kitchen.id, { at: at(14) })).children), [], 'the kitchen was empty at 14:00');
  assert.deepEqual(names((await T.tree(garage.id, { at: at(14) })).children), ['Kettle plug']);
  // already there: nothing is written
  const n = (await all('SELECT id FROM thing_relation')).length;
  assert.equal((await T.moveThing(plug.id, kitchen.id, { at: at(16) })).relation, null);
  assert.equal((await all('SELECT id FROM thing_relation')).length, n);
  // a move made ahead of time is replaced by a later one before it takes effect
  await T.moveThing(plug.id, living.id, { at: at(18, 5) });
  await T.moveThing(plug.id, garage.id, { at: at(17, 5) });                       // a correction made later for an earlier time: the future placement is cancelled
  assert.equal((await T.placeChain(plug.id, { at: at(19) }))[1].name, 'Garage');
  assert.equal((await T.placeChain(plug.id, { at: at(17, 30) }))[1].name, 'Garage');
  assert.equal((await T.placeChain(plug.id, { at: at(17, 0) }))[1].name, 'Kitchen');
  await T.moveThing(plug.id, kitchen.id, { at: at(20) });
});

